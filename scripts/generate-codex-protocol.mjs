#!/usr/bin/env node
// Regenerates the Codex app-server protocol types the Codex chat adapter reads.
//
// Codex publishes its protocol as TypeScript (`codex app-server generate-ts`):
// about 700 files, most of them for surfaces this app never touches (realtime
// audio, account management, fuzzy search). Only the types reachable from the
// messages the adapter handles are kept, so a Codex upgrade shows up as a diff
// here and as type errors where the adapter no longer matches the wire.
//
//   node scripts/generate-codex-protocol.mjs [path-to-codex]

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, mkdirSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'src/main/providers/codex-protocol')
const codex = process.argv[2] ?? 'codex'

// What the adapter sends, and every server message it reads.
const ROOTS = [
  'InitializeParams',
  'v2/ThreadItem',
  'v2/ItemStartedNotification',
  'v2/ItemCompletedNotification',
  'v2/AgentMessageDeltaNotification',
  'v2/ReasoningTextDeltaNotification',
  'v2/ReasoningSummaryTextDeltaNotification',
  'v2/CommandExecutionOutputDeltaNotification',
  'v2/TurnStartedNotification',
  'v2/TurnCompletedNotification',
  'v2/TurnPlanUpdatedNotification',
  'v2/ThreadTokenUsageUpdatedNotification',
  'v2/ErrorNotification',
  'v2/WarningNotification',
  'v2/ConfigWarningNotification',
  'v2/GuardianWarningNotification',
  'v2/DeprecationNoticeNotification',
  'v2/ModelReroutedNotification',
  'v2/McpServerStatusUpdatedNotification',
  'v2/CommandExecutionRequestApprovalParams',
  'v2/FileChangeRequestApprovalParams',
  'v2/ToolRequestUserInputParams',
  'v2/ThreadForkParams',
  'v2/ThreadGoalSetParams',
  'v2/ThreadGoalSetResponse',
  'v2/ThreadGoalGetParams',
  'v2/ThreadGoalGetResponse',
  'v2/ThreadGoalClearParams',
  'v2/ThreadGoalClearResponse',
  'v2/ThreadGoalUpdatedNotification',
  'v2/ThreadGoalClearedNotification',
]

const version = execFileSync(codex, ['--version'], { encoding: 'utf8' }).trim()
const scratch = mkdtempSync(join(tmpdir(), 'codex-protocol-'))
try {
  execFileSync(codex, ['app-server', 'generate-ts', '--out', scratch], { stdio: 'ignore' })
  const kept = new Set()
  const visit = (name) => {
    if (kept.has(name)) return
    const file = join(scratch, `${name}.ts`)
    if (!existsSync(file)) throw new Error(`${version} has no ${name}.ts; update ROOTS.`)
    kept.add(name)
    const source = readFileSync(file, 'utf8')
    for (const [, specifier] of source.matchAll(/from "(\.[^"]+)"/g))
      visit(relative(scratch, resolve(dirname(file), specifier)))
  }
  for (const name of ROOTS) visit(name)
  rmSync(target, { recursive: true, force: true })
  for (const name of [...kept].sort()) {
    const out = join(target, `${name}.ts`)
    mkdirSync(dirname(out), { recursive: true })
    writeFileSync(out, readFileSync(join(scratch, `${name}.ts`), 'utf8'))
  }
  const exports = ROOTS.map((name) => `export type { ${name.split('/').at(-1)} } from './${name}'`)
  writeFileSync(
    join(target, 'index.ts'),
    [
      '// GENERATED by scripts/generate-codex-protocol.mjs. Do not edit by hand.',
      `// Source: ${version}`,
      `export const CODEX_PROTOCOL_VERSION = ${JSON.stringify(version.replace(/^codex-cli\s+/, ''))}`,
      ...exports,
      '',
    ].join('\n'),
  )
  console.log(`Kept ${kept.size} of Codex's protocol types from ${version} in ${relative(root, target)}.`)
} finally {
  rmSync(scratch, { recursive: true, force: true })
}
